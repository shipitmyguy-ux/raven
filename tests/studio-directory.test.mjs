import assert from "node:assert/strict";
import fs from "node:fs";
import "../supabase/functions/_shared/track-filter.js";
const code=fs.readFileSync("supabase/functions/raven-studio-scan/index.ts","utf8");
const providers=fs.readFileSync("supabase/functions/_shared/studio-providers.mjs","utf8");
const {gameArtRoleAllowed,jobLocationAllowed}=globalThis.RavenTrackFilter;
assert.match(code,/raven_studio_sources/);
assert.match(code,/raven_studio_checks/);
assert.match(code,/raven_studio_cron_auth/);
assert.match(code,/x-raven-studio-secret/);
assert.match(code,/crypto\.subtle\.digest\("SHA-256"/);
assert.match(providers,/case 'ashby'/);
assert.match(providers,/case 'greenhouse'/);
assert.match(providers,/case 'lever'/);
assert.match(code,/raven_search_results\?on_conflict=url/);
assert.match(code,/gameArtRoleAllowed\(j\)&&jobLocationAllowed\(j\)/);
assert.equal(gameArtRoleAllowed({title:"Senior Environment Artist"}),true);
assert.equal(gameArtRoleAllowed({title:"Character Artist"}),false);
assert.equal(jobLocationAllowed({location:"Remote - US",remote:true}),true);
assert.equal(jobLocationAllowed({location:"London, UK",remote:false}),false);
console.log("studio directory checks passed");
